"""Typst emission for the generated tables.

Typst cannot read LaTeX, so each generated table reaches the manuscript as two
files written side by side from the same `typeset.Table` as its `.tex`:

    <stem>.table.json  the table as data: header, rows, caption, footer, label
    <stem>.typ         loads <stem>.table.json with `json()` and typesets it
                       as a `figure(kind: table)` with the LaTeX label

The data file is `.table.json`, not `.json`, because `deviations render` may
be pointed at one directory for everything, where `deviations.json` is already
the deviation document itself.

The `.typ` is self-contained -- it imports nothing from the thesis template --
so the manuscript only needs `#include "generated/<stem>.typ"`. Every table is
breakable with a repeated header, so a long one splits across pages the way
its `longtable` counterpart does.

A cell in the JSON is one run or a list of runs, where a run is a string or a
one-key object naming what the text is: `{"mono": ...}`, `{"emph": ...}`,
`{"url": ...}`, `{"sup": ...}`, `{"ident": ...}` (plain text that may break
after `, _ = /`; monospace runs may too). Typst inserts a string as text, never as
markup, so no cell needs escaping. The JSON is not CSV even for the plainest
table because the runs are part of the data (a commit SHA is monospace in
every table that shows one).
"""

import json
import re

from .typeset import DASH as _DASH_SEG
from .typeset import mono as _mono

# The deviation table's commit placeholder for a method with no commits.
_MONO_DASH = _mono("--")

HEADER = (
    "// GENERATED by `{command}` -- do not edit.\n"
    "// Source of truth: {source}\n"
)

# What a Typst `<label>` literal may contain; anything else is written with
# `label("...")`, which takes any string.
_LABEL = re.compile(r"[A-Za-z0-9_\-:.]+")

_COLUMN = re.compile(r"[lrc]|p\{([0-9.]+)\\linewidth\}")

_ALIGN = {"l": "left", "r": "right", "c": "center", "p": "left"}


def data_name(stem):
    return f"{stem}.table.json"


def typst_string(value):
    """A Typst string literal."""
    escaped = (
        str(value)
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


def comment_safe(value):
    """Text for a `//` comment: one line, whatever the campaign path holds.

    `str.splitlines` splits on every line terminator Typst also ends a comment
    at (LF, CR, VT, FF, NEL, U+2028, U+2029), so nothing after one can escape
    the comment into markup.
    """
    return " ".join(str(value).splitlines())


def columns(colspec):
    """Typst (columns, align) from a LaTeX column specification.

    `l`, `r`, `c` become `auto`; `p{<f>\\linewidth}` becomes a fractional
    column in the same proportion, so the paragraph columns share whatever
    width the others leave rather than claiming a fixed share of the page
    that pushes the narrow columns into each other.

    Only what the generators write is understood -- `l`, `r`, `c`,
    `p{<f>\\linewidth}` and the `@{}` padding suppressors -- and anything else
    is refused rather than guessed, so a new LaTeX column type cannot quietly
    produce a Typst table of another shape.
    """
    spec = colspec.replace("@{}", "")
    widths, aligns, position = [], [], 0
    while position < len(spec):
        match = _COLUMN.match(spec, position)
        if not match:
            raise ValueError(f"column spec {colspec!r}: cannot read {spec[position:]!r}")
        token = match.group(0)
        if token.startswith("p"):
            share = float(match.group(1)) * 100
            widths.append(f"{share:g}fr")
            aligns.append(_ALIGN["p"])
        else:
            widths.append("auto")
            aligns.append(_ALIGN[token])
        position = match.end()
    return widths, aligns


# Characters a run may break at, in Typst: whitespace and the identifier
# separators the `.typ` puts boxes around, plus the hyphen, after which the
# Unicode line-break rules allow a break.
_BREAKS = re.compile(r"[\s,_=/\-]")


# How many characters' weight a whole line is worth, used only to weigh a
# `p{f}` column against the content-weighted columns beside it. Tuned on the
# deviation table in the ELTE template (12 pt body, footnote-size table) so
# that `-DBENCH_` fits the `reversible` column; it is a weight, not a measure.
CHARS_PER_LINE = 125

# A content-weighted column claims at most this many characters' worth.
MAX_WEIGHT = 16


def _chars(cell):
    return len("".join(seg.text for seg in cell or []))


def column_spec(table):
    """How each column is sized: `("fit",)`, `("auto",)` or `("fr", weight)`.

    Fitted columns (see `fitted_columns`) take their measured natural width.
    In a table with a paragraph (`p{}`) column -- one meant to fill the line --
    every other column is fractional, weighted by its longest cell in
    characters, and a `p{f}` column weighs `f * CHARS_PER_LINE`; the `.typ`
    turns the weights into widths, never narrower than the widest piece the
    column cannot break. `auto` columns would instead take their full natural
    width first and leave the paragraph columns only what remains. A table
    without a paragraph column keeps `auto` columns and its natural width.
    """
    widths, _ = columns(table.colspec)
    fitted = set(fitted_columns(table))
    paragraph = any(w.endswith("fr") for w in widths)
    out = []
    for index, width in enumerate(widths):
        if index in fitted:
            out.append(("fit",))
        elif not paragraph:
            out.append(("auto",))
        elif width.endswith("fr"):
            share = float(width[:-2]) / 100
            out.append(("fr", round(share * CHARS_PER_LINE, 4)))
        else:
            longest = max(
                [len(table.head[index])] + [_chars(row[index]) for row in table.rows]
            )
            out.append(("fr", min(longest, MAX_WEIGHT)))
    return out


def _typst_spec(spec):
    def one(entry):
        if entry[0] == "fr":
            return f'("fr", {entry[1]:g})'
        return f'("{entry[0]}", 0)'

    return "(" + ", ".join(one(e) for e in spec) + ",)"


def fitted_columns(table):
    """Indices of the columns that hold one unbreakable token per row.

    Commit SHAs are the motivating case, and deviation classes
    (`instrumentation`), statuses and counts are the same: a column narrower
    than such a token cannot wrap it, so the token would overprint the next
    column. The `.typ` measures these columns
    and fixes their width instead. A missing value (the dash, or the
    monospace `--` placeholder) or an empty cell does not disqualify a column; anything else that is not a single
    such token does.
    """
    fitted = []
    for index in range(len(table.head)):
        tokens = 0
        for row in table.rows:
            cell = row[index]
            if not cell or cell == [_DASH_SEG] or cell == [_MONO_DASH]:
                continue
            if (
                len(cell) == 1
                and cell[0].kind in ("text", "ident", "mono")
                and not _BREAKS.search(cell[0].text)
            ):
                tokens += 1
                continue
            break
        else:
            if tokens:
                fitted.append(index)
    return fitted


