"""Typst emission for the generated tables.

Typst cannot read LaTeX, so each generated table reaches the manuscript as two
files written side by side from the same `typeset.Table` as its `.tex`:

    <stem>.table.json  the table as data: header, rows, caption, footer, label
    <stem>.typ         loads <stem>.table.json with `json()` and typesets it
                       as a `figure(kind: table)` with the LaTeX label

The data file is `.table.json`, not `.json`, because `deviations render` may
be pointed at one directory for everything, where `deviations.json` is already
the deviation document itself.

The `.typ` is self-contained -- it imports nothing from the thesis template --
so the manuscript only needs `#include "generated/<stem>.typ"`. Every table is
breakable with a repeated header, so a long one splits across pages the way
its `longtable` counterpart does.

A cell in the JSON is one run or a list of runs, where a run is a string or a
one-key object naming what the text is: `{"mono": ...}`, `{"emph": ...}`,
`{"url": ...}`, `{"sup": ...}`. Typst inserts a string as text, never as
markup, so no cell needs escaping. The JSON is not CSV even for the plainest
table because the runs are part of the data (a commit SHA is monospace in
every table that shows one).
"""

import json
import re

HEADER = (
    "// GENERATED by `{command}` -- do not edit.\n"
    "// Source of truth: {source}\n"
)

# What a Typst `<label>` literal may contain; anything else is written with
# `label("...")`, which takes any string.
_LABEL = re.compile(r"^[A-Za-z0-9_\-:.]+$")

_COLUMN = re.compile(r"[lrc]|p\{([0-9.]+)\\linewidth\}")

_ALIGN = {"l": "left", "r": "right", "c": "center", "p": "left"}


def data_name(stem):
    return f"{stem}.table.json"


def typst_string(value):
    """A Typst string literal."""
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def columns(colspec):
    """Typst (columns, align) from a LaTeX column specification.

    Only what the generators write is understood -- `l`, `r`, `c`,
    `p{<f>\\linewidth}` and the `@{}` padding suppressors -- and anything else
    is refused rather than guessed, so a new LaTeX column type cannot quietly
    produce a Typst table of another shape.
    """
    spec = colspec.replace("@{}", "")
    widths, aligns, position = [], [], 0
    while position < len(spec):
        match = _COLUMN.match(spec, position)
        if not match:
            raise ValueError(f"column spec {colspec!r}: cannot read {spec[position:]!r}")
        token = match.group(0)
        if token.startswith("p"):
            percent = float(match.group(1)) * 100
            widths.append(f"{percent:g}%")
            aligns.append(_ALIGN["p"])
        else:
            widths.append("auto")
            aligns.append(_ALIGN[token])
        position = match.end()
    return widths, aligns


# ---------------------------------------------------------------------------
# JSON
# ---------------------------------------------------------------------------


def run(seg):
    if seg.kind in ("text", "lit"):
        return seg.text
    if seg.kind in ("mono", "emph", "url", "sup"):
        return {seg.kind: seg.text}
    raise ValueError(f"unknown segment kind {seg.kind!r}")


def cell_data(segments):
    """A cell as JSON: its only run when it has one, else the list of runs."""
    runs = []
    for seg in segments or []:
        value = run(seg)
        if isinstance(value, str) and runs and isinstance(runs[-1], str):
            runs[-1] += value
        else:
            runs.append(value)
    if not runs:
        return ""
    return runs[0] if len(runs) == 1 else runs


def data(table, command, source):
    return {
        "generated": f"GENERATED by `{command}` -- do not edit.",
        "source": source,
        "label": table.label,
        "caption": cell_data(table.caption),
        "head": list(table.head),
        "rows": [[cell_data(c) for c in row] for row in table.rows],
        "footer": cell_data(table.footer) if table.footer else None,
    }


def _dump(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def json_text(table, command, source):
    """Deterministic JSON with one table row per line, so a diff is per row."""
    doc = data(table, command, source)
    lines = ["{"]
    keys = sorted(doc)
    for index, key in enumerate(keys):
        comma = "," if index < len(keys) - 1 else ""
        value = doc[key]
        if key == "rows":
            if not value:
                lines.append(f'  "rows": []{comma}')
                continue
            lines.append('  "rows": [')
            for position, row in enumerate(value):
                tail = "," if position < len(value) - 1 else ""
                lines.append(f"    {_dump(row)}{tail}")
            lines.append(f"  ]{comma}")
        else:
            lines.append(f"  {_dump(key)}: {_dump(value)}{comma}")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# .typ
# ---------------------------------------------------------------------------

# Booktabs proportions: heavy outer rules, a lighter one under the header.
HEAVY = "0.08em"
LIGHT = "0.05em"


def source_text(table, stem, command, source):
    """The `.typ` that typesets `<stem>.table.json`.

    Mirrors the LaTeX geometry: a `longtable` has its caption on top and the
    footer between the mid and bottom rules; a `table` float has its caption
    below and the footer under the bottom rule. Both are at footnote size
    (see the comment in the body).
    """
    widths, aligns = columns(table.colspec)
    if len(widths) != len(table.head):
        raise ValueError(
            f"{table.label}: {len(widths)} columns in {table.colspec!r} "
            f"but {len(table.head)} header cells"
        )
    label = (
        f"<{table.label}>"
        if _LABEL.match(table.label)
        else f"#label({typst_string(table.label)})"
    )
    footer_cell = f"table.cell(colspan: {len(widths)}, align: left, cell(data.footer)),"
    if table.long:
        tail = (
            [f"rule({LIGHT}),", footer_cell, f"rule({HEAVY}),"]
            if table.footer
            else [f"rule({HEAVY}),"]
        )
    else:
        tail = [f"rule({HEAVY}),"] + ([footer_cell] if table.footer else [])

    lines = [
        HEADER.format(command=command, source=source).rstrip("\n"),
        f"// Data: {stem}.table.json, next to this file. Typeset with",
        f'//     #include "generated/{stem}.typ"',
        "// Self-contained: needs nothing from the thesis template.",
        "",
        f"#let data = json({typst_string(data_name(stem))})",
        "",
        "// A cell is one run or a list of runs; a run is a string or a one-key",
        "// dictionary naming what its text is.",
        "#let seg(s) = if type(s) == str { s } "
        'else if "mono" in s { raw(s.mono) } '
        'else if "emph" in s { emph(s.emph) } '
        'else if "url" in s { link(s.url, raw(s.url)) } '
        'else if "sup" in s { super(s.sup) } '
        'else { panic("unknown run in generated table: " + repr(s)) }',
        "#let cell(c) = if type(c) == array { c.map(seg).join() } else { seg(c) }",
        "#let rule(w) = table.hline(stroke: w)",
        "",
        "#[",
        "#show figure: set block(breakable: true)",
        "// Identifiers such as `timing,memory,quality` or `MVS_BENCH_PHASES` have no",
        "// break opportunity; without one Typst overprints the next column.",
        '#show table.cell: it => { show regex("[,_=/]"): m => m + sym.zws; it }',
    ]
    if table.long:
        lines.append("#set figure.caption(position: top)")
    lines += [
        "#figure(",
        "  kind: table,",
        "  caption: cell(data.caption),",
        "  {",
    ]
    # Footnote size for every table. The LaTeX `longtable`s are at body size,
    # where their `l` columns simply run into the margin; Typst shrinks an
    # over-wide `auto` column instead and overprints its neighbour, so the
    # long tables are set smaller here rather than allowed to collide.
    lines.append("    set text(size: 0.8em)")
    # A `longtable` never splits a row across a page break; neither does this.
    lines.append("    set table.cell(breakable: false)")
    lines += [
        "    table(",
        f"      columns: ({', '.join(widths)},),",
        f"      align: ({', '.join(aligns)},),",
        "      stroke: none,",
        "      table.header(",
        "        repeat: true,",
        f"        rule({HEAVY}),",
        "        ..data.head.map(cell),",
        f"        rule({LIGHT}),",
        "      ),",
        "      ..data.rows.map(row => row.map(cell)).flatten(),",
    ]
    lines += [f"      {line}" for line in tail]
    lines += [
        "    )",
        "  },",
        ")",
        label,
        "]",
    ]
    return "\n".join(lines) + "\n"


def artefacts(table, directory, stem, command, source):
    """[(path, text)] for `<stem>.table.json` and `<stem>.typ` in `directory`."""
    return [
        (directory / data_name(stem), json_text(table, command, source)),
        (directory / f"{stem}.typ", source_text(table, stem, command, source)),
    ]

